/* ============================================================
   Query 22: Rank Products by Revenue

   Business Question:
   What is the revenue ranking of each product?

   Objective:
   Compare product performance using SQL window functions.

   Approach:
   Calculate product revenue and apply the RANK() function in
   descending order of revenue.

   Expected Outcome:
   Each product with its revenue and ranking position.
============================================================ */

SELECT
    ProductName,
    Revenue,
    RANK() OVER (ORDER BY Revenue DESC) AS RevenueRank
FROM (
    SELECT
        ProductName,
        SUM(NetSales) AS Revenue
    FROM vw_sales
    GROUP BY ProductName
) t;




/* ============================================================
   Query 23: Top Product in Each Category

   Business Question:
   Which product performs best within each category?

   Objective:
   Identify category leaders using ROW_NUMBER().

   Approach:
   Rank products within each category and select the top-ranked
   product.

   Expected Outcome:
   One top-performing product for each category.
============================================================ */

WITH product_revenue AS (
    SELECT
        Category,
        ProductName,
        SUM(NetSales) AS Revenue,
        ROW_NUMBER() OVER (
            PARTITION BY Category
            ORDER BY SUM(NetSales) DESC
        ) AS rn
    FROM vw_sales
    GROUP BY Category, ProductName
)

SELECT
    Category,
    ProductName,
    ROUND(Revenue, 2) AS Revenue
FROM product_revenue
WHERE rn = 1;




/* ============================================================
   Query 24: Running Monthly Revenue

   Business Question:
   How has cumulative revenue grown over time?

   Objective:
   Track cumulative business growth month by month.

   Approach:
   Calculate monthly revenue and apply a running total using
   SUM() OVER().

   Expected Outcome:
   Monthly revenue with cumulative revenue growth.
============================================================ */

WITH monthly_revenue AS (
    SELECT
        DATE_FORMAT(OrderDate, '%Y-%m') AS Month,
        SUM(NetSales) AS Revenue
    FROM vw_sales
    GROUP BY DATE_FORMAT(OrderDate, '%Y-%m')
)

SELECT
    Month,
    ROUND(Revenue, 2) AS Revenue,
    ROUND(
        SUM(Revenue) OVER (ORDER BY Month),
        2
    ) AS RunningRevenue
FROM monthly_revenue;




