/* ============================================================
   Query 10: Monthly Orders Trend

   Business Question:
   How has customer order volume changed over time?

   Objective:
   Analyze customer purchasing activity and business demand.

   Approach:
   Count distinct orders for each month.

   Expected Outcome:
