/* ============================================================
   Query 01: Total Revenue

   Business Question:
   What is the total revenue generated by the company?

   Objective:
   Measure overall sales performance across all transactions.

   Approach:
   Sum the NetSales value from the analytical view (vw_sales),
   where NetSales already accounts for discounts.

   Expected Outcome:
   Total Revenue = 169163902.87
============================================================ */

SELECT ROUND(SUM(NetSales), 2) AS TotalRevenue
FROM vw_sales;




/* ============================================================
   Query 02: Total Profit

   Business Question:
   How much profit has the company earned?

   Objective:
   Evaluate overall business profitability.

   Approach:
   Sum the Profit column, which is calculated as:
   NetSales - TotalCost.

   Expected Outcome:
   Total Profit = 44270425.29
============================================================ */

SELECT ROUND(SUM(Profit), 2) AS TotalProfit
FROM vw_sales;



/* ============================================================
   Query 03: Profit Margin Percentage

   Business Question:
   What percentage of revenue is retained as profit?

   Objective:
   Measure the efficiency and profitability of the business.

   Approach:
   Divide total profit by total revenue and multiply by 100.

   Expected Outcome:
   Profit Margin Percentage = 26.17%
   ============================================================ */

SELECT ROUND(
    SUM(Profit) / SUM(NetSales) * 100,
    2
) AS ProfitMarginPercent
FROM vw_sales;


