/* ============================================================
   Query 07: Average Order Value (AOV)

   Business Question:
   How much revenue does an average order generate?

   Objective:
   Understand customer spending behavior per order.

   Approach:
   First calculate revenue for each order, then compute the
   average of all order revenues.

   Expected Outcome:
   Average revenue generated per order = 4229.10
============================================================ */

SELECT ROUND(
    AVG(OrderRevenue), 2
) AS AverageOrderValue
FROM (
    SELECT OrderID, SUM(NetSales) AS OrderRevenue
    FROM vw_sales
    GROUP BY OrderID
)t;




/* ============================================================
   Query 08: Monthly Revenue Trend

   Business Question:
   How has revenue changed over time?

   Objective:
   Identify growth patterns, seasonality, and high/low
   performing months.

   Approach:
   Group transactions by year and month and calculate total
   revenue for each period.

   Expected Outcome:
   A chronological monthly revenue trend.
============================================================ */

SELECT
    DATE_FORMAT(OrderDate, '%Y-%m') AS Month,
    ROUND(SUM(NetSales), 2) AS Revenue
FROM vw_sales
GROUP BY DATE_FORMAT(OrderDate, '%Y-%m')
ORDER BY Month;



/* ============================================================
   Query 09: Monthly Profit Trend

   Business Question:
   How has profitability changed over time?

   Objective:
   Track profit performance and identify months with unusually
   high or low profitability.

   Approach:
   Group transactions by month and calculate total profit.

   Expected Outcome:
   A monthly profit trend for profitability analysis.
============================================================ */

SELECT
    DATE_FORMAT(OrderDate, '%Y-%m') AS Month,
    ROUND(SUM(Profit), 2) AS Profit
