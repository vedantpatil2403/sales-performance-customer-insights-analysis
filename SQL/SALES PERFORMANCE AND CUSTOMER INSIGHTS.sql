/* ============================================================
   Query 15: Revenue by Age Group

   Business Question:
   Which customer age group contributes the most revenue?

   Objective:
   Understand purchasing behavior across different age segments.

   Approach:
   Create age groups using CASE WHEN and calculate total revenue
   for each group.

   Expected Outcome:
   Revenue contribution of each customer age segment.
============================================================ */

SELECT
    CASE
        WHEN Age BETWEEN 18 AND 25 THEN '18-25'
        WHEN Age BETWEEN 26 AND 35 THEN '26-35'
        WHEN Age BETWEEN 36 AND 45 THEN '36-45'
        WHEN Age BETWEEN 46 AND 55 THEN '46-55'
        ELSE '55+'
    END AS AgeGroup,

    ROUND(SUM(NetSales), 2) AS Revenue,
    COUNT(DISTINCT CustomerID) AS Customers,
    ROUND(AVG(NetSales), 2) AS AvgTransactionValue

FROM vw_sales
GROUP BY AgeGroup
ORDER BY Revenue DESC;




