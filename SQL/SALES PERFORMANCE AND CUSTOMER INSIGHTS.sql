/* ============================================================
   Query 19: Revenue Contribution by Region

   Business Question:
   What percentage of total revenue is contributed by each region?

   Objective:
   Understand the relative importance of each region in overall
   business performance.

   Approach:
   Calculate regional revenue and divide it by total company
   revenue using a window function.

   Expected Outcome:
   Revenue contribution percentage for each region.
============================================================ */

WITH region_revenue AS (
    SELECT
        RegionName,
        SUM(NetSales) AS Revenue
    FROM vw_sales
    GROUP BY RegionName
)

SELECT
    RegionName,
    ROUND(Revenue, 2) AS Revenue,
    ROUND(
        Revenue * 100.0 / SUM(Revenue) OVER (),
        2
    ) AS RevenueContributionPercent
FROM region_revenue
ORDER BY Revenue DESC;

