/* 
   Analytical View: vw_sales

   Purpose:
   Create a business-ready analytical dataset by combining
   customers, products, orders, order details, sales
   representatives, and regions into a single view.

   Why this view is created:
   1. Simplifies SQL analysis by avoiding repeated JOINs.
   2. Ensures consistent calculations for revenue and profit.
   3. Reduces query complexity and improves readability.
   4. Acts as a centralized reporting layer for Excel,
      Power BI, and analytical queries.
   5. Mimics a real-world sales data mart used in analytics
      and business intelligence projects.

   Business Metrics Included:
   - GrossSales
   - DiscountAmount
   - NetSales
   - TotalCost
   - Profit

   Expected Outcome:
   A single analytical view that can be used for KPI reporting,
   trend analysis, product analysis, customer analysis, and
   dashboard development.
*/

USE Sales_Analytics;
USE sales_analytics;

CREATE OR REPLACE VIEW vw_sales AS
SELECT
    od.OrderDetailID,
    o.OrderID,
    o.OrderDate,
    o.PaymentMethod,
    o.OrderStatus,

    c.CustomerID,
    c.FirstName,
    c.LastName,
    c.Gender,
    c.Age,
    c.State,

    p.ProductID,
    p.ProductName,
    p.Category,
    p.Brand,

    sr.RepName,
    r.RegionName,

    od.Quantity,
    od.DiscountPercent,
    p.UnitPrice,
    p.UnitCost,

    -- Business Metrics
    (od.Quantity * p.UnitPrice) AS GrossSales,

    (od.Quantity * p.UnitPrice * od.DiscountPercent/100) AS DiscountAmount,

    (od.Quantity * p.UnitPrice * (1 - od.DiscountPercent/100)) AS NetSales,

    (od.Quantity * p.UnitCost) AS TotalCost,

    ((od.Quantity * p.UnitPrice * (1 - od.DiscountPercent/100))
     - (od.Quantity * p.UnitCost)) AS Profit

FROM order_details od
JOIN orders o ON od.OrderID = o.OrderID
JOIN customers c ON o.CustomerID = c.CustomerID
JOIN products p ON od.ProductID = p.ProductID
JOIN sales_representatives sr ON o.SalesRepID = sr.SalesRepID
JOIN regions r ON sr.RegionID = r.RegionID;

